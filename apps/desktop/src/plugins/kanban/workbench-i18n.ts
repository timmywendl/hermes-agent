// Every existing plugin locale receives the same keys; untranslated locales
// use the English fallback instead of exposing translation paths.
export const WORKBENCH_LOCALES = Object.fromEntries(
  Object.entries(KANBAN_LOCALES).map(([locale, messages]) => [
    locale,
    { ...messages, workbench: locale.startsWith('zh') ? zh : en }
  ])
)

export function useWorkbenchText() {
  const t = usePluginI18n('kanban')

  return (key: keyof typeof en) => t(`workbench.${key}`)
}
